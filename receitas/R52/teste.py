import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from h5166 import *
d = Doc("R52")
d.ex("document.rasterEffectsSettings", {"resolution": 300})
d.rect(0, 0, 1440, 810, "#05080C")
# foto com borda suave: feather direto na imagem borra a foto toda (ver receita), entao usa mascara de opacidade radial
ph = d.image(AM + "/tratado/c-noite.jpg", 600, 120, 800)
m = d.rect(600, 120, 800, 450, "#000000")
d.ex("select.set", {"ids": [m]})
d.ex("paint.setFill", {"gradient": {"kind": "radial", "stops": [{"offset": 0, "color": "#FFFFFF"}, {"offset": 0.55, "color": "#FFFFFF"}, {"offset": 1, "color": "#000000"}]}})
d.ex("select.set", {"ids": [ph, m]})
print("mask", d.ex("transparency.makeOpacityMask", {}))
d.ex("select.none")
# bloco com feather (funciona em forma)
fb = d.rect(560, 600, 800, 120, "#7A5A00")
d.ex("select.set", {"ids": [fb]}); d.ex("effect.apply", {"effect": "stylize.feather", "params": {"radius": 25}}); d.ex("select.none")
t = d.text(60, 300, "NOITE DAS\nESTRELAS", "Helvetica Neue", "Condensed Black", 150, "#FFF6B0", leading=140)
d.ex("select.set", {"ids": [t]})
r = d.ex("effect.apply", {"effect": "stylize.outerGlow", "params": {"blur": 22, "color": Y, "mode": "screen", "opacity": 85}})
print("glow text", r)
d.ex("select.none")
# pilula com glow
p = d.rect(60, 560, 360, 70, "#05080C", stroke=Y, sw=3, radius=35)
d.ex("select.set", {"ids": [p]})
d.ex("effect.apply", {"effect": "stylize.outerGlow", "params": {"blur": 14, "color": Y, "mode": "screen", "opacity": 90}})
d.ex("select.none")
d.text(95, 607, "COTA MASTER", "Helvetica Neue", "Bold", 30, Y)
d.text(60, 720, "Glow em texto vivo, glow em forma, mascara radial em foto e feather em forma (300 ppi)", "Helvetica Neue", "Medium", 16, "#9FA7B0")
p = d.export(); report(p); d.close()
